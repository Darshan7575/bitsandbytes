template <typename T> __device__ int sgn(T val) { return (T(0) < val) - (val < T(0)); }

template <int STOCHASTIC> __device__ unsigned char dQuantize(float* smem_code, const float rand, float x) {
    int pivot = 127;
    int upper_pivot = 255;
    int lower_pivot = 0;

    float lower = -1.0f;
    float upper = 1.0f;

    float val = smem_code[pivot];
    // i>>=1 = {32, 16, 8, 4, 2, 1}
    for (int i = 64; i > 0; i >>= 1) {
        if (x > val) {
            lower_pivot = pivot;
            lower = val;
            pivot += i;
        } else {
            upper_pivot = pivot;
            upper = val;
            pivot -= i;
        }
        val = smem_code[pivot];
    }

    if (upper_pivot == 255)
        upper = smem_code[upper_pivot];
    if (lower_pivot == 0)
        lower = smem_code[lower_pivot];

    if (!STOCHASTIC) {
        if (x > val) {
            float midpoint = (upper + val) * 0.5f;
            if (x > midpoint) {
                return upper_pivot;
            } else
                return pivot;
        } else {
            float midpoint = (lower + val) * 0.5f;
            if (x < midpoint)
                return lower_pivot;
            else
                return pivot;
        }
    } else {
        if (x > val) {
            float dist_to_upper = fabsf(upper - x);
            float dist_full = upper - val;
            if (rand >= dist_to_upper / dist_full)
                return upper_pivot;
            else
                return pivot;
        } else {
            float dist_to_lower = fabsf(lower - x);
            float dist_full = val - lower;
            if (rand >= dist_to_lower / dist_full)
                return lower_pivot;
            else
                return pivot;
        }
    }
}

template <int SIGNED>
__device__ __forceinline__ unsigned char
    quantize_2D(float* __restrict__ quadrants, float* __restrict__ const smem_code, float x) {
    int pivot = 127;
    int upper_pivot = 255;
    int lower_pivot = 0;

    float lower = SIGNED ? -1.0f : 0.0f;
    float upper = 1.0f;
    float midpoint;
    float val = quadrants[1];
    int local_pivot = 1;
    int offset = 1;

    // i>>=1 = {32, 16, 8, 4, 2, 1}
    for (int i = 64; i > 0; i >>= 1) {
        if (x > val) {
            lower_pivot = pivot;
            lower = val;
            pivot += i;
            // val = i == 64 ? quadrants[2] : smem_code[pivot];
            local_pivot += offset;
        } else {
            upper_pivot = pivot;
            upper = val;
            pivot -= i;
            // val = i == 64 ? quadrants[0] : smem_code[pivot];
            local_pivot -= offset;
        }
        val = i >= 64 ? quadrants[local_pivot] : smem_code[pivot];
        offset -= 1;
    }

    if (x > val) {
        midpoint = (upper + val) * 0.5f;
        if (x > midpoint)
            return upper_pivot;
        else
            return pivot;
    } else {
        midpoint = (lower + val) * 0.5f;
        if (x < midpoint)
            return lower_pivot;
        else
            return pivot;
    }
}

template <typename T, int BLOCK_SIZE, int NUM_PER_TH, int STOCHASTIC, int DATA_TYPE>
//__launch_bounds__(TH, 4)
__global__ void kQuantizeBlockwise(
    float* code, T* __restrict__ const A, float* absmax, unsigned char* out, float* __restrict__ const rand,
    const int rand_offset, const int n
) {
    // This can overflow, so we clamp to INT32_MAX. We won't have more elements than this.
    const int n_full = min(gridDim.x * BLOCK_SIZE, INT32_MAX);

    const int base_idx = blockIdx.x * BLOCK_SIZE;
    int valid_items = 0;

    T vals[NUM_PER_TH];
    float rand_vals[NUM_PER_TH];
    unsigned char qvals[(DATA_TYPE > 0) ? NUM_PER_TH / 2 : NUM_PER_TH];

    float local_abs_max = 0.0f;
    int local_rand_idx = 0;

    // WARP_TRANSPOSE requires block_dim >= warp_size. On CDNA (warp=64),
    // block_dim=32 (from BLOCK_SIZE=64/NUM_PER_TH=2) is too small. Fall back
    // to DIRECT load/store in that case.
    static constexpr int THREADS = BLOCK_SIZE / NUM_PER_TH;
    static constexpr auto LOAD_ALGO =
        (THREADS >= BNB_WARP_SIZE) ? bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE : bnb_cub::BLOCK_LOAD_DIRECT;
    static constexpr auto STORE_ALGO =
        (THREADS >= BNB_WARP_SIZE) ? bnb_cub::BLOCK_STORE_WARP_TRANSPOSE : bnb_cub::BLOCK_STORE_DIRECT;

    typedef bnb_cub::BlockLoad<T, THREADS, NUM_PER_TH, LOAD_ALGO> LoadT;
    typedef bnb_cub::BlockStore<unsigned char, THREADS, (DATA_TYPE > 0) ? NUM_PER_TH / 2 : NUM_PER_TH, STORE_ALGO>
        StoreChar;
    typedef bnb_cub::BlockReduce<float, THREADS> BlockReduce;
    typedef bnb_cub::BlockLoad<float, THREADS, NUM_PER_TH, LOAD_ALGO> LoadFloat;

    __shared__ typename LoadT::TempStorage loadt;
    __shared__ typename LoadFloat::TempStorage loadf;
    __shared__ typename StoreChar::TempStorage storec;
    __shared__ typename BlockReduce::TempStorage reduce;
    __shared__ float smem_code[256];
    __shared__ float smem_absmax_value[1];

    if (DATA_TYPE == General8bit)
        for (int i = threadIdx.x; i < 256; i += blockDim.x)
            smem_code[i] = code[i];

    for (int64_t i = base_idx; i < n_full; i += gridDim.x * BLOCK_SIZE) {
        valid_items = min(BLOCK_SIZE, static_cast<int>(n - i));
        local_abs_max = -FLT_MAX;

        __syncthreads();
        LoadT(loadt).Load(&(A[i]), vals, valid_items, (T)0.0f);

        // 1. compute local max
        // 2. broadcast local max
        // 3. normalize inputs and quantize

#pragma unroll NUM_PER_TH
        for (int j = 0; j < NUM_PER_TH; j++)
            local_abs_max = fmaxf(local_abs_max, fabsf((float)vals[j]));

        local_abs_max = BlockReduce(reduce).Reduce(local_abs_max, BNB_MAX_OP, valid_items);

        if (threadIdx.x == 0) {
            smem_absmax_value[0] = 1.0f / local_abs_max;
            absmax[i / BLOCK_SIZE] = local_abs_max;
        }
        __syncthreads();

        local_abs_max = smem_absmax_value[0];

        if (STOCHASTIC) {
            local_rand_idx = ((blockIdx.x * NUM_BLOCK) + (threadIdx.x * NUM) + rand_offset) % (1024 - 4);
            LoadFloat(loadf).Load(&rand[local_rand_idx], rand_vals, BLOCK_SIZE, 0);
        }

        switch (DATA_TYPE) {
        case General8bit:
#pragma unroll NUM_PER_TH
            for (int j = 0; j < NUM_PER_TH; j++) {
                if (!STOCHASTIC)
                    qvals[j] = dQuantize<0>(smem_code, 0.0f, ((float)vals[j]) * local_abs_max);
                else
                    qvals[j] = dQuantize<1>(smem_code, rand_vals[j], ((float)vals[j]) * local_abs_max);
            }
            break;
        case FP4:
#pragma unroll NUM_PER_TH
            for (int j = 0; j < NUM_PER_TH / 2; j++) {
                qvals[j] = dQuantizeFP4(((float)vals[2 * j]) * local_abs_max) << 4;
                qvals[j] |= dQuantizeFP4(((float)vals[2 * j + 1]) * local_abs_max);
            }
            break;
        case NF4:
#pragma unroll NUM_PER_TH
            for (int j = 0; j < NUM_PER_TH / 2; j++) {
                qvals[j] = dQuantizeNF4(((float)vals[2 * j]) * local_abs_max) << 4;
                qvals[j] |= dQuantizeNF4(((float)vals[2 * j + 1]) * local_abs_max);
            }
            break;
        }

        __syncthreads();
        StoreChar(storec).Store(
            &(out[(DATA_TYPE > 0) ? i / 2 : i]), qvals, (DATA_TYPE > 0) ? (valid_items + 1) / 2 : valid_items
        );
    }
}

// Small-blocksize kernel for 4-bit quantization, parameterized on quantization
// block size (QBLOCK_SIZE).  Always launches exactly BNB_WARP_SIZE threads so
// every lane in the wavefront is productive.  Multiple quantization blocks are
// packed into one wavefront when QBLOCK_SIZE < BNB_WARP_SIZE * NUM_PER_TH:
//
//   CDNA (64), QBLOCK_SIZE=32 -> 4 quant blocks per wavefront
//   CDNA (64), QBLOCK_SIZE=64 -> 2 quant blocks per wavefront
//   CUDA/RDNA (32), QBLOCK_SIZE=32 -> 2 quant blocks per wavefront
//
// Uses logical-warp WarpReduce<THREADS_PER_QB> so each quantization block's
// threads reduce independently via warp shuffles.
template <typename T, int QBLOCK_SIZE, int DATA_TYPE>
__global__ void kQuantizeBlockwiseSmall(
    float* code, T* __restrict__ const A, float* absmax, unsigned char* out, float* __restrict__ const rand,
    const int rand_offset, const int n
) {
    static_assert(QBLOCK_SIZE <= BNB_WARP_SIZE * 2, "QBLOCK_SIZE too large for one warp");

    constexpr int NUM_PER_TH = 2;
    constexpr int THREADS = BNB_WARP_SIZE;
    constexpr int THREADS_PER_QB = QBLOCK_SIZE / NUM_PER_TH;
    constexpr int NUM_QB = THREADS / THREADS_PER_QB;
    constexpr int TOTAL_VALUES = QBLOCK_SIZE * NUM_QB;

    const int base_idx = blockIdx.x * TOTAL_VALUES;

    T vals[NUM_PER_TH];
    unsigned char qvals[NUM_PER_TH / 2];
    float local_abs_max = 0.0f;

    const int qb_id = threadIdx.x / THREADS_PER_QB;
    const int local_tid = threadIdx.x % THREADS_PER_QB;

    typedef bnb_cub::BlockLoad<T, THREADS, NUM_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadT;
    typedef bnb_cub::BlockStore<unsigned char, THREADS, NUM_PER_TH / 2, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreChar;
    typedef bnb_cub::WarpReduce<float, THREADS_PER_QB> WarpReduce;

    __shared__ typename LoadT::TempStorage loadt;
    __shared__ typename StoreChar::TempStorage storec;
    __shared__ typename WarpReduce::TempStorage warp_reduce[NUM_QB];
    __shared__ float smem_absmax_value[NUM_QB];

    const int qi = base_idx + qb_id * QBLOCK_SIZE;
    const bool qb_valid = (qi < n);

    __syncthreads();
    LoadT(loadt).Load(&(A[base_idx]), vals, min(TOTAL_VALUES, n - base_idx), (T)0.0f);

    local_abs_max = -FLT_MAX;
#pragma unroll NUM_PER_TH
    for (int j = 0; j < NUM_PER_TH; j++)
        local_abs_max = fmaxf(local_abs_max, fabsf((float)vals[j]));

    local_abs_max = WarpReduce(warp_reduce[qb_id]).Reduce(local_abs_max, BNB_MAX_OP);

    if (local_tid == 0) {
        if (qb_valid) {
            smem_absmax_value[qb_id] = 1.0f / local_abs_max;
            absmax[blockIdx.x * NUM_QB + qb_id] = local_abs_max;
        } else {
            smem_absmax_value[qb_id] = 0.0f;
        }
    }
    __syncthreads();

    local_abs_max = smem_absmax_value[qb_id];

    switch (DATA_TYPE) {
    case FP4:
#pragma unroll NUM_PER_TH
        for (int j = 0; j < NUM_PER_TH / 2; j++) {
            qvals[j] = dQuantizeFP4(((float)vals[2 * j]) * local_abs_max) << 4;
            qvals[j] |= dQuantizeFP4(((float)vals[2 * j + 1]) * local_abs_max);
        }
        break;
    case NF4:
#pragma unroll NUM_PER_TH
        for (int j = 0; j < NUM_PER_TH / 2; j++) {
            qvals[j] = dQuantizeNF4(((float)vals[2 * j]) * local_abs_max) << 4;
            qvals[j] |= dQuantizeNF4(((float)vals[2 * j + 1]) * local_abs_max);
        }
        break;
    }

    __syncthreads();
    StoreChar(storec).Store(&(out[base_idx / 2]), qvals, min((TOTAL_VALUES + 1) / 2, (n - base_idx + 1) / 2));
}

template <typename T, int TILE_SIZE, int THREADS, int NUM_PER_TH, int DATA_TYPE>
__global__ void
    kDequantizeBlockwise(float* code, unsigned char* A, float* absmax, T* out, const int blocksize, const int n) {

    const int n_load = (gridDim.x * TILE_SIZE);
    int valid_items_load = 0;
    int valid_items_store = 0;
    const int base_idx = (blockIdx.x * TILE_SIZE);

    T vals[NUM_PER_TH * ((DATA_TYPE > 0) ? 2 : 1)];
    unsigned char qvals[NUM_PER_TH];
    float local_abs_max = -FLT_MAX;

    typedef bnb_cub::BlockLoad<unsigned char, THREADS, NUM_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadChar;
    typedef bnb_cub::BlockStore<T, THREADS, NUM_PER_TH*((DATA_TYPE > 0) ? 2 : 1), bnb_cub::BLOCK_STORE_WARP_TRANSPOSE>
        StoreT;

    __shared__ typename LoadChar::TempStorage loadchar;
    __shared__ typename StoreT::TempStorage storet;

    for (int i = base_idx; i < n_load; i += gridDim.x * TILE_SIZE) {
        if (DATA_TYPE > 0) {
            // Cast n to int64_t to avoid overflow for large n
            valid_items_load = min(TILE_SIZE, static_cast<int>((static_cast<int64_t>(n) + 1) / 2) - i);
            valid_items_store = min(TILE_SIZE * 2, n - i * 2);
        } else {
            valid_items_load = min(TILE_SIZE, n - i);
            valid_items_store = valid_items_load;
        }

        // Since blocksize will always be a power-of-2, we avoid more expensive
        // division by the blocksize and instead use a shift operation.
        // This is equivalent to (i+threadId.x*NUM_PER_TH)/blocksize.
        local_abs_max = __ldg(&absmax[(i + threadIdx.x * NUM_PER_TH) >> (31 - __clz(blocksize))]);

        __syncthreads();
        LoadChar(loadchar).Load(&(A[i]), qvals, valid_items_load, 128);

        switch (DATA_TYPE) {
        case General8bit:
// load code through read-only cache via __ldg
#pragma unroll NUM_PER_TH
            for (int j = 0; j < NUM_PER_TH; j++)
                vals[j] = __ldg(&code[qvals[j]]) * local_abs_max;
            break;
        case FP4:
#pragma unroll NUM_PER_TH
            for (int j = 0; j < NUM_PER_TH; j++) {
                vals[j * 2] = dDequantizeFP4Tree(qvals[j] >> 4) * local_abs_max;
                vals[j * 2 + 1] = dDequantizeFP4Tree(qvals[j] & 0x0F) * local_abs_max;
            }
            break;
        case NF4:
#pragma unroll NUM_PER_TH
            for (int j = 0; j < NUM_PER_TH; j++) {
                vals[j * 2] = dDequantizeNF4(qvals[j] >> 4) * local_abs_max;
                vals[j * 2 + 1] = dDequantizeNF4(qvals[j] & 0x0F) * local_abs_max;
            }
            break;
        }

        __syncthreads();
        StoreT(storet).Store(&(out[(DATA_TYPE > 0) ? i * 2 : i]), vals, valid_items_store);
    }
}

template <typename T, int OPTIMIZER, int BLOCK_SIZE, int NUM_VALS>
__launch_bounds__(BLOCK_SIZE / NUM_VALS, 1) __global__ void kPreconditionOptimizer32bit2State(
    T* g, T* p, float* state1, float* state2, float* unorm, const float beta1, const float beta2, const float eps,
    const float weight_decay, const int step, const float lr, const float gnorm_scale, const int n
) {

    const int n_full = (BLOCK_SIZE * (n / BLOCK_SIZE)) + (n % BLOCK_SIZE == 0 ? 0 : BLOCK_SIZE);
    const int base_idx = (blockIdx.x * blockDim.x * NUM_VALS);
    int valid_items = 0;

    T g_vals[NUM_VALS];

    float s1_vals[NUM_VALS];
    float s2_vals[NUM_VALS];

    const float correction1 = 1.0f / (1.0f - powf(beta1, step));
    const float correction2 = 1.0f / (1.0f - powf(beta2, step));

    typedef bnb_cub::BlockLoad<T, BLOCK_SIZE / NUM_VALS, NUM_VALS, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> Load;
    typedef bnb_cub::BlockLoad<float, BLOCK_SIZE / NUM_VALS, NUM_VALS, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadFloat;
    typedef bnb_cub::BlockReduce<float, BLOCK_SIZE / NUM_VALS> BlockReduce;

    __shared__ union {
        typename Load::TempStorage load;
        typename LoadFloat::TempStorage loadf;
        typename BlockReduce::TempStorage reduce;
    } temp_storage;

    for (unsigned int i = base_idx; i < n_full; i += gridDim.x * BLOCK_SIZE) {
        valid_items = n - i >= (BLOCK_SIZE) ? (BLOCK_SIZE) : n - i;

        __syncthreads();
        Load(temp_storage.load).Load(&(g[i]), g_vals, valid_items, 0.0f);
        __syncthreads();
        LoadFloat(temp_storage.loadf).Load(&(state1[i]), s1_vals, valid_items, 0.0f);
        __syncthreads();
        LoadFloat(temp_storage.loadf).Load(&(state2[i]), s2_vals, valid_items, 0.0f);

#pragma unroll NUM_VALS
        for (unsigned int j = 0; j < NUM_VALS; j++)
            g_vals[j] = gnorm_scale * ((float)g_vals[j]);

#pragma unroll NUM_VALS
        for (unsigned int j = 0; j < NUM_VALS; j++) {
            switch (OPTIMIZER) {
            case ADAM:
                s1_vals[j] = s1_vals[j] * beta1 + ((1.0f - beta1) * ((float)g_vals[j]));
                s2_vals[j] = s2_vals[j] * beta2 + ((1.0f - beta2) * (((float)g_vals[j]) * ((float)g_vals[j])));
                s1_vals[j] *= correction1;
                s2_vals[j] *= correction2;
                s1_vals[j] = s1_vals[j] / (sqrtf(s2_vals[j]) + eps); // update
                s1_vals[j] *= s1_vals[j];                            // update l2 norm (update*update)
                break;
            case ADEMAMIX:
                break;
            }
        }

#pragma unroll NUM_VALS - 1
        for (unsigned int j = 1; j < NUM_VALS; j++)
            s1_vals[0] += s1_vals[j];

        __syncthreads();
        s1_vals[0] = BlockReduce(temp_storage.reduce).Sum(s1_vals[0]);

        if (threadIdx.x == 0)
            atomicAdd(&unorm[0], s1_vals[0]);

        __syncwarp();
    }
}

#define NUM_PER_THREAD 4

template <typename T, int OPTIMIZER>
__launch_bounds__(TH, 1) __global__ void kOptimizer32bit2State(
    T* g, T* p, float* state1, float* state2, float* unorm, const float max_unorm, const float param_norm,
    const float beta1, const float beta2, const float beta3, const float alpha, const float eps,
    const float weight_decay, const int step, const float lr, const float gnorm_scale, const bool skip_zeros,
    const int n
) {

    const int n_full = ((TH * NUM_PER_THREAD) * (n / (TH * NUM_PER_THREAD))) +
                       (n % (TH * NUM_PER_THREAD) == 0 ? 0 : (TH * NUM_PER_THREAD));
    const int base_idx = (blockIdx.x * blockDim.x * NUM_PER_THREAD);
    int valid_items = 0;
    float update_scale = 0.0f;
    T g_vals[NUM_PER_THREAD];
    T p_vals[NUM_PER_THREAD];

    float s1_vals[NUM_PER_THREAD];
    float s2_vals[NUM_PER_THREAD];

    // AdEMAMix has an additional state buffer, which we packed
    // into state1. We need thread-local storage here for these.
    // TODO: Mark with [[maybe_unused]] after upgrade to min compiler.
    float s3_vals[NUM_PER_THREAD];

    const float correction1 = 1.0f - powf(beta1, step);
    const float correction2 = sqrtf(1.0f - powf(beta2, step));
    const float step_size = -lr * correction2 / correction1;

    if (max_unorm > 0.0f) {
        update_scale = max_unorm > 0.0f ? sqrtf(unorm[0]) : 1.0f;
        if (update_scale > max_unorm * param_norm) {
            update_scale = (max_unorm * param_norm) / update_scale;
        } else {
            update_scale = 1.0f;
        }
    } else {
        update_scale = 1.0f;
    }

    typedef bnb_cub::BlockLoad<T, TH, NUM_PER_THREAD, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> Load;
    typedef bnb_cub::BlockStore<T, TH, NUM_PER_THREAD, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> Store;

    typedef bnb_cub::BlockLoad<float, TH, NUM_PER_THREAD, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadFloat;
    typedef bnb_cub::BlockStore<float, TH, NUM_PER_THREAD, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreFloat;

    __shared__ union {
        typename Load::TempStorage load;
        typename Store::TempStorage store;
        typename LoadFloat::TempStorage loadf;
        typename StoreFloat::TempStorage storef;
    } temp_storage;

    for (unsigned int i = base_idx; i < n_full; i += gridDim.x * TH * NUM_PER_THREAD) {
        valid_items = n - i >= (TH * NUM_PER_THREAD) ? (TH * NUM_PER_THREAD) : n - i;

        __syncthreads();
        Load(temp_storage.load).Load(&(g[i]), g_vals, valid_items);
        __syncthreads();
        LoadFloat(temp_storage.loadf).Load(&(state1[i]), s1_vals, valid_items);
        __syncthreads();
        LoadFloat(temp_storage.loadf).Load(&(state2[i]), s2_vals, valid_items);
        __syncthreads();
        Load(temp_storage.load).Load(&(p[i]), p_vals, valid_items);

        // Load additional state1 data for AdEMAMix
        // TODO: Make constexpr after updating min compiler
        if (OPTIMIZER == ADEMAMIX) {
            __syncthreads();
            LoadFloat(temp_storage.loadf).Load(&(state1[n + i]), s3_vals, valid_items);
        }

#pragma unroll 4
        for (unsigned int j = 0; j < NUM_PER_THREAD; j++)
            g_vals[j] = gnorm_scale * ((float)g_vals[j]);

#pragma unroll 4
        for (unsigned int j = 0; j < NUM_PER_THREAD; j++) {
            switch (OPTIMIZER) {
            case ADEMAMIX:
                // m1 update: m1 = beta1 * m1 + (1-beta1) * g
                s1_vals[j] = (s1_vals[j] * beta1) + ((1.0f - beta1) * (float)g_vals[j]);

                // m2 update: m2 = m2 * beta3 + (1-beta3) * g
                s3_vals[j] = (s3_vals[j] * beta3) + ((1.0f - beta3) * (float)g_vals[j]);

                // nu update: nu = beta2 * nu + (1-beta2) * g^2
                s2_vals[j] = (s2_vals[j] * beta2) + ((1.0f - beta2) * (float)g_vals[j] * (float)g_vals[j]);

                p_vals[j] = (float)p_vals[j] - lr * (((s1_vals[j] / correction1) + (alpha * s3_vals[j])) /
                                                     ((sqrtf(s2_vals[j]) / correction2) + eps));

                if (weight_decay > 0.0f)
                    p_vals[j] = ((float)p_vals[j]) * (1.0f - (lr * weight_decay));

                break;
            case ADAM:

                if (!skip_zeros || (skip_zeros && ((float)g_vals[j] != 0.0f))) {
                    s1_vals[j] = s1_vals[j] * beta1 + ((1.0f - beta1) * ((float)g_vals[j]));
                    s2_vals[j] = s2_vals[j] * beta2 + ((1.0f - beta2) * (((float)g_vals[j]) * ((float)g_vals[j])));
                    p_vals[j] = ((float)p_vals[j]) +
                                (update_scale * step_size * (s1_vals[j] / (sqrtf(s2_vals[j]) + (eps * correction2))));

                    if (weight_decay > 0.0f)
                        p_vals[j] = ((float)p_vals[j]) * (1.0f - (lr * weight_decay));
                }
                break;
            }
        }

        __syncthreads();
        Store(temp_storage.store).Store(&(p[i]), p_vals, valid_items);
        __syncthreads();
        StoreFloat(temp_storage.storef).Store(&(state1[i]), s1_vals, valid_items);
        __syncthreads();
        StoreFloat(temp_storage.storef).Store(&(state2[i]), s2_vals, valid_items);

        if (OPTIMIZER == ADEMAMIX) {
            __syncthreads();
            StoreFloat(temp_storage.storef).Store(&(state1[n + i]), s3_vals, valid_items);
        }
    }
}

template <typename T, int OPTIMIZER, int BLOCK_SIZE, int NUM_VALS>
__launch_bounds__(BLOCK_SIZE / NUM_VALS, 1) __global__ void kPreconditionOptimizer32bit1State(
    T* g, T* p, float* state1, float* unorm, const float beta1, const float beta2, const float eps,
    const float weight_decay, const int step, const float lr, const float gnorm_scale, const int n
) {

    const int n_full = (BLOCK_SIZE * (n / BLOCK_SIZE)) + (n % BLOCK_SIZE == 0 ? 0 : BLOCK_SIZE);
    const int base_idx = (blockIdx.x * blockDim.x * NUM_VALS);
    int valid_items = 0;

    T g_vals[NUM_VALS];

    float s1_vals[NUM_VALS];

    typedef bnb_cub::BlockLoad<T, BLOCK_SIZE / NUM_VALS, NUM_VALS, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> Load;
    typedef bnb_cub::BlockLoad<float, BLOCK_SIZE / NUM_VALS, NUM_VALS, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadFloat;
    typedef bnb_cub::BlockReduce<float, BLOCK_SIZE / NUM_VALS> BlockReduce;

    __shared__ union {
        typename Load::TempStorage load;
        typename LoadFloat::TempStorage loadf;
        typename BlockReduce::TempStorage reduce;
    } temp_storage;

    for (unsigned int i = base_idx; i < n_full; i += gridDim.x * BLOCK_SIZE) {
        valid_items = n - i >= (BLOCK_SIZE) ? (BLOCK_SIZE) : n - i;

        __syncthreads();
        Load(temp_storage.load).Load(&(g[i]), g_vals, valid_items, 0.0f);
        __syncthreads();
        LoadFloat(temp_storage.loadf).Load(&(state1[i]), s1_vals, valid_items, 0.0f);

#pragma unroll NUM_VALS
        for (unsigned int j = 0; j < NUM_VALS; j++)
            g_vals[j] = gnorm_scale * ((float)g_vals[j]);

#pragma unroll NUM_VALS
        for (unsigned int j = 0; j < NUM_VALS; j++) {
            switch (OPTIMIZER) {
            case MOMENTUM:
                if (step == 1)
                    s1_vals[j] = (float)g_vals[j]; // state update
                else
                    s1_vals[j] = s1_vals[j] * beta1 + ((float)g_vals[j]); // state update
                s1_vals[j] = s1_vals[j] * s1_vals[j];                     // update norm
                break;
            case LION:
                s1_vals[j] = s1_vals[j] * beta2 + ((1.0f - beta2) * (float)g_vals[j]); // state update
                break;
            case RMSPROP:
                s1_vals[j] =
                    s1_vals[j] * beta1 + ((1.0f - beta1) * ((float)g_vals[j]) * ((float)g_vals[j])); // state update
                s1_vals[j] = __fdividef((float)g_vals[j], sqrtf(s1_vals[j]) + eps);                  // update value
                s1_vals[j] = s1_vals[j] * s1_vals[j];                                                // update norm
                break;
            case ADAGRAD:
                s1_vals[j] = s1_vals[j] + ((float)g_vals[j]) * ((float)g_vals[j]);  // state update
                s1_vals[j] = __fdividef((float)g_vals[j], sqrtf(s1_vals[j]) + eps); // update value
                s1_vals[j] = s1_vals[j] * s1_vals[j];                               // update norm
                break;
            }
        }

#pragma unroll
        for (unsigned int j = 1; j < NUM_VALS; j++)
            s1_vals[0] += s1_vals[j];

        __syncthreads();
        s1_vals[0] = BlockReduce(temp_storage.reduce).Sum(s1_vals[0], valid_items);

        if (threadIdx.x == 0)
            atomicAdd(&unorm[0], s1_vals[0]);

        __syncwarp();
    }
}

template <typename T, int OPTIMIZER>
__launch_bounds__(TH, 1) __global__ void kOptimizer32bit1State(
    T* g, T* p, float* state1, float* unorm, const float max_unorm, const float param_norm, const float beta1,
    const float beta2, const float eps, const float weight_decay, const int step, const float lr,
    const float gnorm_scale, const bool skip_zeros, const int n
) {

    const int n_full = ((TH * NUM_PER_THREAD) * (n / (TH * NUM_PER_THREAD))) +
                       (n % (TH * NUM_PER_THREAD) == 0 ? 0 : (TH * NUM_PER_THREAD));
    const int base_idx = (blockIdx.x * blockDim.x * NUM_PER_THREAD);
    int valid_items = 0;
    float update_scale = 0.0f;

    if (max_unorm > 0.0f) {
        update_scale = max_unorm > 0.0f ? sqrtf(unorm[0]) : 1.0f;
        if (update_scale > max_unorm * param_norm + eps) {
            update_scale = (max_unorm * param_norm + eps) / update_scale;
        } else {
            update_scale = 1.0f;
        }
    } else {
        update_scale = 1.0f;
    }

    T g_vals[NUM_PER_THREAD];
    T p_vals[NUM_PER_THREAD];

    float s1_vals[NUM_PER_THREAD];

    typedef bnb_cub::BlockLoad<T, TH, NUM_PER_THREAD, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> Load;
    typedef bnb_cub::BlockStore<T, TH, NUM_PER_THREAD, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> Store;

    typedef bnb_cub::BlockLoad<float, TH, NUM_PER_THREAD, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadFloat;
    typedef bnb_cub::BlockStore<float, TH, NUM_PER_THREAD, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreFloat;

    __shared__ union {
        typename Load::TempStorage load;
        typename Store::TempStorage store;
        typename LoadFloat::TempStorage loadf;
        typename StoreFloat::TempStorage storef;
    } temp_storage;

    for (unsigned int i = base_idx; i < n_full; i += gridDim.x * TH * NUM_PER_THREAD) {
        valid_items = n - i >= (TH * NUM_PER_THREAD) ? (TH * NUM_PER_THREAD) : n - i;

        __syncthreads();
        Load(temp_storage.load).Load(&(g[i]), g_vals, valid_items);
        __syncthreads();
        LoadFloat(temp_storage.loadf).Load(&(state1[i]), s1_vals, valid_items);
        __syncthreads();
        Load(temp_storage.load).Load(&(p[i]), p_vals, valid_items);

#pragma unroll 4
        for (unsigned int j = 0; j < NUM_PER_THREAD; j++) {
            g_vals[j] = gnorm_scale * ((float)g_vals[j]);
            // Coupled (L2) weight decay folds decay into the gradient. Correct for
            // MOMENTUM/RMSPROP/ADAGRAD, but NOT for LION, which uses decoupled
            // (AdamW-style) decay applied to the param directly (see the LION branch
            // below and Chen et al. 2023). This matches the CUDA 8-bit blockwise kernel.
            if (weight_decay > 0.0f && OPTIMIZER != LION)
                g_vals[j] = (float)g_vals[j] + (((float)p_vals[j]) * weight_decay);
        }

#pragma unroll 4
        for (unsigned int j = 0; j < NUM_PER_THREAD; j++) {
            if (!skip_zeros || (skip_zeros && ((float)g_vals[j] != 0.0f))) {
                switch (OPTIMIZER) {
                case MOMENTUM:
                    if (step == 1)
                        s1_vals[j] = (float)g_vals[j];
                    else
                        s1_vals[j] = s1_vals[j] * beta1 + ((float)g_vals[j]);

                    p_vals[j] = ((float)p_vals[j]) + update_scale * (-lr * (s1_vals[j]));
                    break;
                case LION:
                    // Decoupled weight decay: shrink the param directly, outside the
                    // sign update (Chen et al. 2023), matching the 8-bit blockwise kernel.
                    if (weight_decay > 0.0f)
                        p_vals[j] = ((float)p_vals[j]) * (1.0f - lr * weight_decay);
                    p_vals[j] =
                        ((float)p_vals[j]) -
                        update_scale * (lr * sgn(((float)s1_vals[j]) * beta1 + ((1.0f - beta1) * ((float)g_vals[j]))));
                    s1_vals[j] = s1_vals[j] * beta2 + ((1.0f - beta2) * ((float)g_vals[j]));
                    break;
                case RMSPROP:
                    s1_vals[j] = s1_vals[j] * beta1 + ((1.0f - beta1) * ((float)g_vals[j]) * ((float)g_vals[j]));
                    p_vals[j] = ((float)p_vals[j]) -
                                update_scale * (lr * __fdividef((float)g_vals[j], sqrtf((float)s1_vals[j]) + eps));
                    break;
                case ADAGRAD:
                    s1_vals[j] = s1_vals[j] + ((float)g_vals[j]) * ((float)g_vals[j]);
                    p_vals[j] = ((float)p_vals[j]) - lr * __fdividef((float)g_vals[j], sqrtf((float)s1_vals[j]) + eps);
                    break;
                }
            }
        }

        __syncthreads();
        Store(temp_storage.store).Store(&(p[i]), p_vals, valid_items);
        __syncthreads();
        StoreFloat(temp_storage.storef).Store(&(state1[i]), s1_vals, valid_items);
    }
}

#define LANES 2
#define QUAD 3

template <typename T, int OPTIMIZER, int BLOCK_SIZE, int N_PER_TH>
__launch_bounds__(256, 3) __global__ void kOptimizerStatic8bit2StateBlockwise(
    T* p, T* __restrict__ const g, unsigned char* state1, unsigned char* state2, const float beta1, const float beta2,
    const float beta3, const float alpha, const float eps, const int step, const float lr,
    float* __restrict__ const quantiles1, float* __restrict__ const quantiles2, float* absmax1, float* absmax2,
    float weight_decay, const float gnorm_scale, const bool skip_zeros, const int n
) {

    // const int n_full = n + (n%BLOCK_SIZE);
    const int n_full = gridDim.x * BLOCK_SIZE;
    const int base_idx = (blockIdx.x * BLOCK_SIZE);
    int valid_items = 0;
    float g_val = 0.0f;
    float s1_vals[N_PER_TH];
    float s2_vals[N_PER_TH];
    float s3_vals[N_PER_TH];

    // 2-5%
    const float correction1 = 1.0f - __powf(beta1, step);
    const float correction2 = sqrtf(1.0f - __powf(beta2, step));
    const float step_size = __fdividef(-lr * correction2, correction1);
    const int lane_id = threadIdx.x % LANES;
    float new_local_abs_max1 = -FLT_MAX;
    float new_local_abs_max2 = -FLT_MAX;
    float new_local_abs_max3 = -FLT_MAX;
    float quadrants1[QUAD];
    float quadrants2[QUAD];

    unsigned char c1s[N_PER_TH];
    unsigned char c2s[N_PER_TH];
    unsigned char c3s[N_PER_TH];

    T g_vals[N_PER_TH];
    T p_vals[N_PER_TH];
    typedef bnb_cub::BlockLoad<T, BLOCK_SIZE / N_PER_TH, N_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadT;
    typedef bnb_cub::BlockLoad<unsigned char, BLOCK_SIZE / N_PER_TH, N_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE>
        LoadChar;

    typedef bnb_cub::BlockStore<unsigned char, BLOCK_SIZE / N_PER_TH, N_PER_TH, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE>
        StoreChar;
    typedef bnb_cub::BlockStore<T, BLOCK_SIZE / N_PER_TH, N_PER_TH, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreT;

    __shared__ float smem_quantiles1[LANES][257];
    __shared__ float smem_quantiles2[LANES][257];
    typedef bnb_cub::BlockReduce<float, BLOCK_SIZE / N_PER_TH> BlockReduce1;
    typedef bnb_cub::BlockReduce<float, BLOCK_SIZE / N_PER_TH> BlockReduce2;
    typedef bnb_cub::BlockReduce<float, BLOCK_SIZE / N_PER_TH> BlockReduce3;
    __shared__ typename BlockReduce1::TempStorage reduce1;
    __shared__ typename BlockReduce2::TempStorage reduce2;
    __shared__ typename BlockReduce2::TempStorage reduce3;
    __shared__ float smem_exchange1[1];
    __shared__ float smem_exchange2[1];
    __shared__ float smem_exchange3[1]; // [[maybe_unused]]

    __shared__ union {
        typename LoadT::TempStorage loadh;
        typename LoadChar::TempStorage loadc;
        typename StoreChar::TempStorage storec;
        typename StoreT::TempStorage storeh;
    } temp_storage;

    // init: 0.2 -> 0.23

    // 0.23 -> 0.23
    smem_quantiles1[0][threadIdx.x] = quantiles1[threadIdx.x];
    smem_quantiles2[0][threadIdx.x] = quantiles2[threadIdx.x];
#pragma unroll
    for (unsigned int j = 1; j < LANES; j++) {
        smem_quantiles1[j][threadIdx.x] = smem_quantiles1[0][threadIdx.x];
        smem_quantiles2[j][threadIdx.x] = smem_quantiles2[0][threadIdx.x];
    }

    __syncthreads();

#pragma unroll
    for (int k = 0; k < QUAD; k++) {
        quadrants1[k] = smem_quantiles1[lane_id][(k * 256 / (QUAD + 1)) + (256 / (QUAD + 1) - 1)];
        quadrants2[k] = smem_quantiles2[lane_id][(k * 256 / (QUAD + 1)) + (256 / (QUAD + 1) - 1)];
    }

    for (unsigned int i = base_idx; i < n_full; i += gridDim.x * BLOCK_SIZE) {
        // loads: 0.23 -> 0.85/1.44
        valid_items = n - i >= BLOCK_SIZE ? BLOCK_SIZE : n - i;
        __syncthreads();
        LoadT(temp_storage.loadh).Load(&(g[i]), g_vals, valid_items, (T)0.0f);
        __syncthreads();
        LoadChar(temp_storage.loadc).Load(&(state1[i]), c1s, valid_items, 128);
        __syncthreads();
        LoadChar(temp_storage.loadc).Load(&(state2[i]), c2s, valid_items, 0);

        // AdEMAMix has an additional state packed into state1.
        if (OPTIMIZER == ADEMAMIX) {
            __syncthreads();
            LoadChar(temp_storage.loadc).Load(&(state1[n + i]), c3s, valid_items, 128);
        }

        new_local_abs_max1 = -FLT_MAX;
        new_local_abs_max2 = -FLT_MAX;
        new_local_abs_max3 = -FLT_MAX;

//  update: 2.48/1.57 -> 2.51/1.60
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            if (!isnan((float)g_vals[j]) && !isinf((float)g_vals[j])) {
                s2_vals[j] = smem_quantiles2[lane_id][c2s[j]] * absmax2[i / BLOCK_SIZE];
                g_val = g_vals[j];
                // float ratio = (g_val*g_val)/fmaxf(s2_vals[j], eps*eps);
                // g_val = ratio > 2.0f ? 2.0f*g_val/ratio : g_val;
                g_val *= gnorm_scale;

                s2_vals[j] = (s2_vals[j] * beta2) + (((1.0f - beta2) * g_val * g_val));

                s1_vals[j] = smem_quantiles1[lane_id][c1s[j]] * absmax1[i / BLOCK_SIZE];
                s1_vals[j] = (s1_vals[j] * beta1) + (((1.0f - beta1) * g_val));

                if (OPTIMIZER == ADEMAMIX) {
                    // The absmax for the third state is appended to absmax1
                    s3_vals[j] = smem_quantiles1[lane_id][c3s[j]] * absmax1[(n + i) / BLOCK_SIZE];
                    s3_vals[j] = (s3_vals[j] * beta3) + (((1.0f - beta3) * g_val));
                }
            } else {
                s1_vals[j] = 0.0f;
                s2_vals[j] = 0.0f;

                if (OPTIMIZER == ADEMAMIX) {
                    s3_vals[j] = 0.0f;
                }
            }

            new_local_abs_max1 = fmaxf(new_local_abs_max1, fabsf(s1_vals[j]));
            new_local_abs_max2 = fmaxf(new_local_abs_max2, fabsf(s2_vals[j]));

            if (OPTIMIZER == ADEMAMIX) {
                new_local_abs_max3 = fmaxf(new_local_abs_max3, fabsf(s3_vals[j]));
            }
        }

        //  reduce: 2.51/1.60 -> 2.67/1.69
        new_local_abs_max1 = BlockReduce1(reduce1).Reduce(new_local_abs_max1, BNB_MAX_OP);
        new_local_abs_max2 = BlockReduce2(reduce2).Reduce(new_local_abs_max2, BNB_MAX_OP);

        if (OPTIMIZER == ADEMAMIX) {
            new_local_abs_max3 = BlockReduce3(reduce3).Reduce(new_local_abs_max3, BNB_MAX_OP);
        }

        if (threadIdx.x == 0) {
            smem_exchange1[0] = new_local_abs_max1;
            smem_exchange2[0] = new_local_abs_max2;

            if (OPTIMIZER == ADEMAMIX) {
                smem_exchange3[0] = new_local_abs_max3;
            }
        }

        __syncthreads();

        if (threadIdx.x == 0) {
            absmax1[i / BLOCK_SIZE] = new_local_abs_max1;
            absmax2[i / BLOCK_SIZE] = new_local_abs_max2;

            if (OPTIMIZER == ADEMAMIX) {
                absmax1[(n + i) / BLOCK_SIZE] = new_local_abs_max3;
            }
        } else {
            new_local_abs_max1 = smem_exchange1[0];
            new_local_abs_max2 = smem_exchange2[0];

            if (OPTIMIZER == ADEMAMIX) {
                new_local_abs_max3 = smem_exchange3[0];
            }
        }

        __syncthreads();
        LoadT(temp_storage.loadh).Load(&(p[i]), p_vals, valid_items, (T)0.0f);
//  reduce: 2.67/1.69 -> 2.67/1.70
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            // if(!skip_zeros || (skip_zeros && ((float)g_vals[j] != 0.0f)))
            if (!isnan((float)g_vals[j]) && !isinf((float)g_vals[j])) {
                if (OPTIMIZER == ADEMAMIX) {
                    p_vals[j] =
                        T((float)p_vals[j] - lr * (((s1_vals[j] / correction1) + (alpha * s3_vals[j])) /
                                                   ((sqrtf(s2_vals[j]) / correction2) + eps)));
                } else {
                    p_vals[j] =
                        (T)(((float)p_vals[j]) +
                            ((step_size * (__fdividef(s1_vals[j], (sqrtf(s2_vals[j]) + (correction2 * eps)))))));
                }

                if (weight_decay > 0.0f)
                    p_vals[j] = ((float)p_vals[j]) * (1.0f - (lr * weight_decay));
            }
        }

        //  store: 0.85/1.44 -> 2.48/1.57
        __syncthreads();
        StoreT(temp_storage.storeh).Store(&(p[i]), p_vals, valid_items);

//  quantizaztion: 2.67/1.70  -> 3.4/3.3
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            c1s[j] = quantize_2D<1>(quadrants1, smem_quantiles1[lane_id], __fdividef(s1_vals[j], new_local_abs_max1));
            c2s[j] = quantize_2D<0>(quadrants2, smem_quantiles2[lane_id], __fdividef(s2_vals[j], new_local_abs_max2));

            // make sure state1 term has still the same sign after quantization
            // (not needed for state2 term which has only positive values)
            if (signbit(smem_quantiles1[lane_id][c1s[j]]) != signbit(s1_vals[j])) {
                if (s1_vals[j] > 0.0f)
                    c1s[j] += 1;
                else
                    c1s[j] -= 1;
            }

            if (OPTIMIZER == ADEMAMIX) {
                c3s[j] =
                    quantize_2D<1>(quadrants1, smem_quantiles1[lane_id], __fdividef(s3_vals[j], new_local_abs_max3));

                if (signbit(smem_quantiles1[lane_id][c3s[j]]) != signbit(s3_vals[j])) {
                    c3s[j] += (s3_vals[j] > 0.0f) ? 1 : -1;
                }
            }
        }

        __syncthreads();
        StoreChar(temp_storage.storec).Store(&(state1[i]), c1s, valid_items);
        __syncthreads();
        StoreChar(temp_storage.storec).Store(&(state2[i]), c2s, valid_items);

        if (OPTIMIZER == ADEMAMIX) {
            __syncthreads();
            StoreChar(temp_storage.storec).Store(&(state1[n + i]), c3s, valid_items);
        }
    }
}

#define LANES 2
#define QUAD 3

template <typename T, int OPTIMIZER, int BLOCK_SIZE, int N_PER_TH>
__launch_bounds__(256, 3) __global__ void kOptimizerStatic8bit1StateBlockwise(
    T* p, T* __restrict__ const g, unsigned char* state1, const float beta1, const float beta2, const float eps,
    const int step, const float lr, float* __restrict__ const quantiles1, float* absmax1, float weight_decay,
    const float gnorm_scale, const bool skip_zeros, const int n
) {

    // const int n_full = n + (n%BLOCK_SIZE);
    const int n_full = gridDim.x * BLOCK_SIZE;
    const int base_idx = (blockIdx.x * BLOCK_SIZE);
    int valid_items = 0;
    float g_val = 0.0f;
    float s1_vals[N_PER_TH];
    // 2-5%
    const int lane_id = threadIdx.x % LANES;
    float new_local_abs_max1 = -FLT_MAX;
    float quadrants1[QUAD];

    unsigned char c1s[N_PER_TH];
    T g_vals[N_PER_TH];
    T p_vals[N_PER_TH];

    typedef bnb_cub::BlockLoad<T, BLOCK_SIZE / N_PER_TH, N_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadT;
    typedef bnb_cub::BlockLoad<unsigned char, BLOCK_SIZE / N_PER_TH, N_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE>
        LoadChar;

    typedef bnb_cub::BlockStore<unsigned char, BLOCK_SIZE / N_PER_TH, N_PER_TH, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE>
        StoreChar;
    typedef bnb_cub::BlockStore<T, BLOCK_SIZE / N_PER_TH, N_PER_TH, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreT;

    __shared__ float smem_quantiles1[LANES][257];
    typedef bnb_cub::BlockReduce<float, BLOCK_SIZE / N_PER_TH> BlockReduce1;
    __shared__ typename BlockReduce1::TempStorage reduce1;
    __shared__ float smem_exchange1[1];

    __shared__ union {
        typename LoadT::TempStorage loadh;
        typename LoadChar::TempStorage loadc;
        typename StoreChar::TempStorage storec;
        typename StoreT::TempStorage storeh;
    } temp_storage;

    // init: 0.2 -> 0.23

    // 0.23 -> 0.23
    smem_quantiles1[0][threadIdx.x] = quantiles1[threadIdx.x];
#pragma unroll
    for (unsigned int j = 1; j < LANES; j++)
        smem_quantiles1[j][threadIdx.x] = smem_quantiles1[0][threadIdx.x];

    __syncthreads();

#pragma unroll
    for (int k = 0; k < QUAD; k++)
        quadrants1[k] = smem_quantiles1[lane_id][(k * 256 / (QUAD + 1)) + (256 / (QUAD + 1) - 1)];

    for (unsigned int i = base_idx; i < n_full; i += gridDim.x * BLOCK_SIZE) {
        // loads: 0.23 -> 0.85/1.44
        valid_items = n - i >= BLOCK_SIZE ? BLOCK_SIZE : n - i;
        __syncthreads();
        LoadT(temp_storage.loadh).Load(&(g[i]), g_vals, valid_items, (T)0.0f);
        __syncthreads();
        LoadChar(temp_storage.loadc).Load(&(state1[i]), c1s, valid_items, 128);
        __syncthreads();
        LoadT(temp_storage.loadh).Load(&(p[i]), p_vals, valid_items, (T)0.0f);

        new_local_abs_max1 = -FLT_MAX;

//  update: 2.48/1.57 -> 2.51/1.60
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            g_val = float(g_vals[j]);
            g_val *= gnorm_scale;
            if (!skip_zeros || (skip_zeros && ((float)g_vals[j] != 0.0f))) {
                if (weight_decay > 0.0f) {
                    switch (OPTIMIZER) {
                    case MOMENTUM:
                    case ADAGRAD:
                    case RMSPROP:
                        g_val += ((float)p_vals[j]) * weight_decay;
                        break;
                    case LION:
                        p_vals[j] = ((float)p_vals[j]) * (1.0f - lr * weight_decay);
                        break;
                    }
                }

                s1_vals[j] = smem_quantiles1[lane_id][c1s[j]] * absmax1[i / BLOCK_SIZE];

                switch (OPTIMIZER) {
                case MOMENTUM:
                    if (step == 1)
                        s1_vals[j] = g_val;
                    else
                        s1_vals[j] = (s1_vals[j] * beta1) + g_val;
                    break;
                case LION:
                    // here, using gvals[j] to store the gradient smoothed by beta1 for the following parameter update,
                    // before the momentum is updated by beta2
                    g_vals[j] = lr * sgn(((float)s1_vals[j]) * beta1 + ((1.0f - beta1) * g_val));
                    s1_vals[j] = s1_vals[j] * beta2 + ((1.0f - beta2) * g_val);
                    break;
                case RMSPROP:
                    s1_vals[j] = s1_vals[j] * beta1 + ((1.0f - beta1) * (g_val * g_val));
                    break;
                case ADAGRAD:
                    s1_vals[j] = s1_vals[j] + (g_val * g_val);
                    break;
                }
            }

            new_local_abs_max1 = fmaxf(new_local_abs_max1, fabsf(s1_vals[j]));
        }

        //  reduce: 2.51/1.60 -> 2.67/1.69
        new_local_abs_max1 = BlockReduce1(reduce1).Reduce(new_local_abs_max1, BNB_MAX_OP);

        if (threadIdx.x == 0)
            smem_exchange1[0] = new_local_abs_max1;

        __syncthreads();

        if (threadIdx.x == 0)
            absmax1[i / BLOCK_SIZE] = new_local_abs_max1;
        else
            new_local_abs_max1 = smem_exchange1[0];

//  reduce: 2.67/1.69 -> 2.67/1.70
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            if (!skip_zeros || (skip_zeros && ((float)g_vals[j] != 0.0f))) {
                switch (OPTIMIZER) {
                case MOMENTUM:
                    p_vals[j] = ((float)p_vals[j]) - lr * (s1_vals[j]);
                    break;
                case LION:
                    p_vals[j] = ((float)p_vals[j]) - ((float)g_vals[j]);
                    break;
                case RMSPROP:
                    g_val = g_vals[j];
                    p_vals[j] = ((float)p_vals[j]) - lr * (__fdividef(g_val, sqrtf(s1_vals[j]) + eps));
                    break;
                case ADAGRAD:
                    g_val = g_vals[j];
                    p_vals[j] = ((float)p_vals[j]) - lr * (__fdividef(g_val, sqrtf(s1_vals[j]) + eps));
                    break;
                }
            }
        }

        //  store: 0.85/1.44 -> 2.48/1.57
        __syncthreads();
        StoreT(temp_storage.storeh).Store(&(p[i]), p_vals, valid_items);

//  quantizaztion: 2.67/1.70  -> 3.4/3.3
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            c1s[j] = quantize_2D<1>(quadrants1, smem_quantiles1[lane_id], __fdividef(s1_vals[j], new_local_abs_max1));

            // make sure state1 term has still the same sign after quantization
            // (not needed for state2 term which has only positive values)
            if (signbit(smem_quantiles1[lane_id][c1s[j]]) != signbit(s1_vals[j])) {
                if (s1_vals[j] > 0.0f)
                    c1s[j] += 1;
                else
                    c1s[j] -= 1;
            }
        }

        __syncthreads();
        StoreChar(temp_storage.storec).Store(&(state1[i]), c1s, valid_items);
    }
}

// ReAdam quantization map for U_t (paper eq. 6). With b bits, 1 bit holds the sign and the remaining b-1 bits index
// 2N magnitudes, N = 2^(b-2):
//   ids [0, N-1]   : N levels log-spaced from eps to 0.1 (inclusive)      eps * (0.1/eps)^(k/(N-1))
//   ids [N, 2N-1]  : N levels linearly spaced above 0.1 up to 1.0        0.1 + 0.9 * m / N,  m = 1..N
// For b = 2 (N = 1) the map degenerates to {eps, 1.0}.
template <int OPTIMIZER_BITS> __device__ __forceinline__ float readam_level(int mag_id, const float eps) {
    constexpr int N = 1 << (OPTIMIZER_BITS - 2);
    if (mag_id < N) {
        if constexpr (N == 1)
            return eps;
        else
            return expf(logf(eps) + ((float)mag_id / (N - 1)) * (logf(0.1f) - logf(eps)));
    }
    return 0.1f + 0.9f * (float)(mag_id - N + 1) / N;
}

// `vals` is the array of signed values containing `8/OPTIMIZER_BITS` entries which are packed into 1 byte.
template <int OPTIMIZER_BITS>
__device__ __forceinline__ unsigned char quantize_update(const float* vals, const bool* in_decay, const float eps) {

    constexpr int N = 1 << (OPTIMIZER_BITS - 2); // magnitude levels per region
    constexpr int SIGN_BIT = 1 << (OPTIMIZER_BITS - 1);

    unsigned char packed_byte = 0;

#pragma unroll
    for (int j = 0; j < (8 / OPTIMIZER_BITS); ++j) {
        float val = vals[j];

        bool is_negative = val < 0.0f;
        // Clamp magnitude to [eps, 1.0f]
        float mag = fminf(fmaxf(fabsf(val), eps), 1.0f);

        int mag_id;
        if constexpr (N == 1) {
            // 2-bit: levels {eps, 1.0}, pick the nearest one.
            mag_id = mag > 0.5f ? 1 : 0;
        } else if (mag <= 0.1f) {
            // Log region: round in log space to one of the N levels in [eps, 0.1].
            float t = (logf(mag) - logf(eps)) / (logf(0.1f) - logf(eps));
            mag_id = min((int)roundf(t * (N - 1)), N - 1);
        } else {
            // Linear region: m = 0 corresponds to 0.1 (the top log level, id N-1), m = 1..N to ids N..2N-1.
            int m = (int)roundf((mag - 0.1f) * (N / 0.9f));
            mag_id = N - 1 + min(m, N);
        }

        // incase the coordinate is in the decay regime, move one step closer towards zero (paper eq. 7).
        mag_id = (in_decay[j] && mag_id > 0) ? mag_id - 1 : mag_id;

        unsigned char val_ind = (unsigned char)mag_id;
        if (is_negative)
            val_ind |= SIGN_BIT;

        packed_byte |= (val_ind << (j * OPTIMIZER_BITS));
    }

    return packed_byte;
}

// `packed_x` is the bit packed representation from which this function extracts and dequantizes `ind` element.
template <int OPTIMIZER_BITS>
__device__ __forceinline__ float dequantize_update(unsigned char packed_x, int ind, const float eps) {

    constexpr unsigned char PACKED_MASK = (1 << OPTIMIZER_BITS) - 1;
    constexpr int SIGN_BIT = 1 << (OPTIMIZER_BITS - 1);

    unsigned char val_ind = (packed_x >> (ind * OPTIMIZER_BITS)) & PACKED_MASK;
    float mag = readam_level<OPTIMIZER_BITS>(val_ind & (SIGN_BIT - 1), eps);

    // Apply sign (MSB holds sign)
    mag = (val_ind & SIGN_BIT) ? -mag : mag;

    return mag;
}

#define LANES 2
#define QUAD 3

template <typename T, int OPTIMIZER_BITS, int NUM_THREADS>
__launch_bounds__(256, 3) __global__ void kOptimizerStaticReadam1D(
    T* p, T* __restrict__ const g, unsigned char* state1, unsigned char* state2, const float beta1, const float beta2,
    const float eps, const int step, const float lr, float* __restrict__ const quantiles2, float* absmax2,
    float weight_decay, float decay_ratio, const float gnorm_scale, const bool skip_zeros, const int n
) {

    constexpr int N_PER_TH = 8 / OPTIMIZER_BITS;
    constexpr int BLOCK_SIZE = NUM_THREADS * N_PER_TH;
    constexpr int ZERO_IND_STATE1 = 1 << (OPTIMIZER_BITS - 1);
    constexpr int ZERO_IND_STATE2 = 128; // for 8 bit, this is the middle value, which indicates zero.

    const int n_full = gridDim.x * BLOCK_SIZE;
    const int base_idx = (blockIdx.x * BLOCK_SIZE);
    int valid_items = 0;
    int valid_items_packed = 0;
    float z_val = 0.0f;
    float s1_vals[N_PER_TH];
    float s2_vals[N_PER_TH];
    bool s1_in_decay[N_PER_TH];

    const float at = __fdividef(1.0f - beta1, 1.0f - __powf(beta1, step));
    const float bt = __fdividef(1.0f - beta2, 1.0f - __powf(beta2, step));
    const int lane_id = threadIdx.x % LANES;
    float new_local_abs_max2 = -FLT_MAX;
    float quadrants2[QUAD];

    unsigned char c1s[1]; // each thread always handles one value from state1, which contains bit packed values for
                          // N_PER_TH number of elements.
    unsigned char c2s[N_PER_TH];
    T g_vals[N_PER_TH];
    T p_vals[N_PER_TH];

    // TODO (darshan): For ampere/hopper architectures, here we could use cp.async instructions to hide the memory
    // latencies behind computations.
    typedef bnb_cub::BlockLoad<T, NUM_THREADS, N_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadT;

    typedef bnb_cub::BlockLoad<unsigned char, NUM_THREADS, N_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadChar;
    typedef bnb_cub::BlockLoad<unsigned char, NUM_THREADS, 1, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadCharPacked;

    typedef bnb_cub::BlockStore<unsigned char, NUM_THREADS, N_PER_TH, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreChar;
    typedef bnb_cub::BlockStore<unsigned char, NUM_THREADS, 1, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreCharPacked;

    typedef bnb_cub::BlockStore<T, NUM_THREADS, N_PER_TH, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreT;

    __shared__ float smem_quantiles2[LANES][257];
    typedef bnb_cub::BlockReduce<float, NUM_THREADS> BlockReduce2;
    __shared__ typename BlockReduce2::TempStorage reduce2;
    __shared__ float smem_exchange2[1];

    __shared__ union {
        typename LoadT::TempStorage loadh;
        typename LoadChar::TempStorage loadc;
        typename LoadCharPacked::TempStorage loadcpacked;
        typename StoreChar::TempStorage storec;
        typename StoreCharPacked::TempStorage storecpacked;
        typename StoreT::TempStorage storeh;
    } temp_storage;

    // init: 0.2 -> 0.23

    // 0.23 -> 0.23
    smem_quantiles2[0][threadIdx.x] = quantiles2[threadIdx.x];
#pragma unroll
    for (unsigned int j = 1; j < LANES; j++)
        smem_quantiles2[j][threadIdx.x] = smem_quantiles2[0][threadIdx.x];

    __syncthreads();

#pragma unroll
    for (int k = 0; k < QUAD; k++)
        quadrants2[k] = smem_quantiles2[lane_id][(k * 256 / (QUAD + 1)) + (256 / (QUAD + 1) - 1)];

    for (unsigned int i = base_idx; i < n_full; i += gridDim.x * BLOCK_SIZE) {
        unsigned int i_packed = i / N_PER_TH;
        // loads: 0.23 -> 0.85/1.44
        valid_items = n - i >= BLOCK_SIZE ? BLOCK_SIZE : n - i;
        valid_items_packed = (valid_items + N_PER_TH - 1) / N_PER_TH;
        __syncthreads();
        LoadT(temp_storage.loadh).Load(&(g[i]), g_vals, valid_items, (T)0.0f);
        __syncthreads();
        LoadCharPacked(temp_storage.loadcpacked).Load(&(state1[i_packed]), c1s, valid_items_packed, ZERO_IND_STATE1);
        __syncthreads();
        LoadChar(temp_storage.loadc).Load(&(state2[i]), c2s, valid_items, ZERO_IND_STATE2);
        __syncthreads();
        LoadT(temp_storage.loadh).Load(&(p[i]), p_vals, valid_items, (T)0.0f);

        new_local_abs_max2 = -FLT_MAX;

//  update: 2.48/1.57 -> 2.51/1.60
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            if (!isnan((float)g_vals[j]) && !isinf((float)g_vals[j])) {
                if (step == 1) {
                    const float g_f = (float)g_vals[j];
                    s1_vals[j] = (float)((g_f > 0.0f) - (g_f < 0.0f));
                    s2_vals[j] = (sqrtf(bt) * fabsf(g_vals[j]));
                    s1_in_decay[j] = false;
                } else {
                    s1_vals[j] = dequantize_update<OPTIMIZER_BITS>(c1s[0], j, eps);
                    s2_vals[j] = smem_quantiles2[lane_id][c2s[j]] * absmax2[i / BLOCK_SIZE];

                    z_val = __fdividef(g_vals[j], s2_vals[j] + eps);

                    float denom = sqrtf(1.0f - bt + (bt * z_val * z_val));

                    s1_vals[j] = __fdividef(((1.0f - at) * s1_vals[j]) + (at * z_val), denom + eps);
                    s2_vals[j] = (s2_vals[j] == 0.0f) ? (sqrtf(bt) * fabsf(g_vals[j])) : (s2_vals[j] * denom);

                    s1_in_decay[j] = (fabsf(s1_vals[j]) > (fabsf(z_val) * decay_ratio));
                }

            } else {
                s1_vals[j] = 0.0f;
                s2_vals[j] = 0.0f;
                s1_in_decay[j] = false;
            }

            new_local_abs_max2 = fmaxf(new_local_abs_max2, fabsf(s2_vals[j]));
        }

        new_local_abs_max2 = BlockReduce2(reduce2).Reduce(new_local_abs_max2, BNB_MAX_OP);

        if (threadIdx.x == 0)
            smem_exchange2[0] = new_local_abs_max2;

        __syncthreads();

        if (threadIdx.x == 0)
            absmax2[i / BLOCK_SIZE] = new_local_abs_max2;
        else
            new_local_abs_max2 = smem_exchange2[0];

        __syncthreads();

//  reduce: 2.67/1.69 -> 2.67/1.70
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            if (!isnan((float)g_vals[j]) && !isinf((float)g_vals[j])) {
                p_vals[j] = (T)(((float)p_vals[j]) - lr * s1_vals[j]);
            }

            if (weight_decay > 0.0f)
                p_vals[j] = ((float)p_vals[j]) * (1.0f - (lr * weight_decay));
        }

        //  store: 0.85/1.44 -> 2.48/1.57
        __syncthreads();
        StoreT(temp_storage.storeh).Store(&(p[i]), p_vals, valid_items);

        //  quantizaztion: 2.67/1.70  -> 3.4/3.3
        c1s[0] = quantize_update<OPTIMIZER_BITS>(s1_vals, s1_in_decay, eps);
        __syncthreads();
        StoreCharPacked(temp_storage.storecpacked).Store(&(state1[i_packed]), c1s, valid_items_packed);
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            c2s[j] = quantize_2D<1>(quadrants2, smem_quantiles2[lane_id], __fdividef(s2_vals[j], new_local_abs_max2));
        }
        __syncthreads();
        StoreChar(temp_storage.storec).Store(&(state2[i]), c2s, valid_items);
    }
}

template <typename T, int OPTIMIZER_BITS, int NUM_THREADS>
__launch_bounds__(256, 3) __global__ void kOptimizerStaticReadam(
    T* p, T* __restrict__ const g, unsigned char* state1, float* __restrict__ const state2_row,
    float* __restrict__ const state2_col, float* __restrict__ const state2_mean, const float beta1, const float beta2,
    const float eps, const int step, const float lr, float weight_decay, float decay_ratio, const float gnorm_scale,
    const bool skip_zeros, const int n, const int n_rows, const int n_cols, const int stride_full
) {
    constexpr int N_PER_TH = 8 / OPTIMIZER_BITS;
    constexpr int BLOCK_SIZE = NUM_THREADS * N_PER_TH;
    constexpr int ZERO_IND = 1 << (OPTIMIZER_BITS - 1);

    const int n_full = gridDim.x * BLOCK_SIZE;
    const int base_idx = (blockIdx.x * BLOCK_SIZE);

    int valid_items = 0;
    int valid_items_packed = 0;
    float z_val = 0.0f;
    float s1_vals[N_PER_TH];
    float s2_val;
    bool s1_in_decay[N_PER_TH];

    const float at = __fdividef(1.0f - beta1, 1.0f - __powf(beta1, step));
    const float beta2_tprev = 1.0f - __powf(beta2, step - 1);
    const float bt = __fdividef(1.0f - beta2, 1.0f - __powf(beta2, step));
    const float eps_sq = eps * eps;

    unsigned char c1s[1]; // each thread always handles one value from state1, which contains bit packed values for
                          // N_PER_TH number of elements.
    T g_vals[N_PER_TH];
    T p_vals[N_PER_TH];

    // TODO (darshan): For ampere/hopper architectures, here we could use cp.async instructions to hide the memory
    // latencies behind computations.
    typedef bnb_cub::BlockLoad<T, NUM_THREADS, N_PER_TH, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadT;
    typedef bnb_cub::BlockStore<T, NUM_THREADS, N_PER_TH, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreT;

    typedef bnb_cub::BlockLoad<unsigned char, NUM_THREADS, 1, bnb_cub::BLOCK_LOAD_WARP_TRANSPOSE> LoadCharPacked;
    typedef bnb_cub::BlockStore<unsigned char, NUM_THREADS, 1, bnb_cub::BLOCK_STORE_WARP_TRANSPOSE> StoreCharPacked;

    __shared__ union {
        typename LoadT::TempStorage loadh;
        typename LoadCharPacked::TempStorage loadcpacked;
        typename StoreCharPacked::TempStorage storecpacked;
        typename StoreT::TempStorage storeh;
    } temp_storage;

    // init: 0.2 -> 0.23

    for (unsigned int i = base_idx; i < n_full; i += gridDim.x * BLOCK_SIZE) {
        const int thread_base_idx = i + (threadIdx.x * N_PER_TH);
        int batch_idx = thread_base_idx / stride_full;
        int state2_row_idx =
            thread_base_idx /
            n_cols; // simplifying the calculations leads to this simple formula to find start idx of row.
        int state2_col_base_idx = (batch_idx * n_cols);
        int state2_col_idx = (thread_base_idx % n_cols);

        // Threads past the end of the tensor (last block) must not read the factored statistics: their row/batch
        // indices point beyond state2_row/state2_mean.
        float row_val = 0.0f;
        float mean_val = 0.0f;
        if (thread_base_idx < n) {
            row_val = __ldg(&state2_row[state2_row_idx]);
            mean_val = __ldg(&state2_mean[batch_idx]);
        }

        unsigned int i_packed = i / N_PER_TH;
        // loads: 0.23 -> 0.85/1.44
        valid_items = n - i >= BLOCK_SIZE ? BLOCK_SIZE : n - i;
        valid_items_packed = (valid_items + N_PER_TH - 1) / N_PER_TH;
        __syncthreads();
        LoadT(temp_storage.loadh).Load(&(g[i]), g_vals, valid_items, (T)0.0f);
        __syncthreads();
        LoadCharPacked(temp_storage.loadcpacked).Load(&(state1[i_packed]), c1s, valid_items_packed, ZERO_IND);
        __syncthreads();
        LoadT(temp_storage.loadh).Load(&(p[i]), p_vals, valid_items, (T)0.0f);
        __syncthreads();

//  update: 2.48/1.57 -> 2.51/1.60
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            if (j > 0) {
                state2_col_idx++;
                if (state2_col_idx == n_cols) {
                    state2_col_idx = 0;
                    state2_row_idx++;
                    // Update batch_idx only if we cross a batch boundary (each batch has n_rows rows)
                    batch_idx = state2_row_idx / n_rows;
                    state2_col_base_idx = (batch_idx * n_cols);

                    if (thread_base_idx + (int)j < n) {
                        row_val = __ldg(&state2_row[state2_row_idx]);
                        mean_val = __ldg(&state2_mean[batch_idx]);
                    }
                }
            }

            // padding elements (beyond n) are never stored, so they are treated like invalid gradients here
            if (thread_base_idx + (int)j < n && !isnan((float)g_vals[j]) && !isinf((float)g_vals[j])) {
                s1_vals[j] = dequantize_update<OPTIMIZER_BITS>(c1s[0], j, eps);

                if (step == 1) {
                    // U_1 = sign(G_1), with sign(0) = 0 so that coordinates without gradient do not move
                    // (matches Adam, where M_1 = 0 for those coordinates).
                    const float g_f = (float)g_vals[j];
                    s1_vals[j] = (float)((g_f > 0.0f) - (g_f < 0.0f));
                    s1_in_decay[j] = false;
                } else {
                    // Here, we use the equations from algorithm 2 of the original Adafactor paper to reconstruct
                    // state2. We do not use any advanced update clipping mechanisms that the original paper proposes in
                    // section 6.
                    s2_val = __fdividef(
                        row_val * __ldg(&state2_col[state2_col_base_idx + state2_col_idx]), mean_val + eps_sq
                    ); // pytorch adafactor implementation uses eps1 instead of eps^2, which is passed as additional
                    // argument.
                    s2_val = sqrtf(__fdividef(s2_val, beta2_tprev));

                    z_val = __fdividef(g_vals[j], s2_val + eps);

                    s1_vals[j] = __fdividef(
                        ((1.0f - at) * s1_vals[j]) + (at * z_val), sqrtf(1 - bt + (bt * z_val * z_val)) + eps
                    );
                    s1_in_decay[j] = (fabsf(s1_vals[j]) > (fabsf(z_val) * decay_ratio));
                }

                // if(threadIdx.x == 0){
                //     printf("after update: %f, %f, %f, %f, %f \n", s1_vals[j], (float)g_vals[j], at, bt, beta2_tprev);
                // }

            } else {
                s1_vals[j] = 0.0f;
                s1_in_decay[j] = false;
            }
        }

//  reduce: 2.67/1.69 -> 2.67/1.70
#pragma unroll N_PER_TH
        for (unsigned int j = 0; j < N_PER_TH; j++) {
            if (!isnan((float)g_vals[j]) && !isinf((float)g_vals[j])) {
                p_vals[j] = (T)(((float)p_vals[j]) - lr * s1_vals[j]);
            }

            if (weight_decay > 0.0f)
                p_vals[j] = ((float)p_vals[j]) * (1.0f - (lr * weight_decay));
        }

        //  store: 0.85/1.44 -> 2.48/1.57
        __syncthreads();
        StoreT(temp_storage.storeh).Store(&(p[i]), p_vals, valid_items);

        //  quantizaztion: 2.67/1.70  -> 3.4/3.3
        c1s[0] = quantize_update<OPTIMIZER_BITS>(s1_vals, s1_in_decay, eps);
        __syncthreads();
        StoreCharPacked(temp_storage.storecpacked).Store(&(state1[i_packed]), c1s, valid_items_packed);
    }
}

// ---------------------------------------------------------------------------------------------------------------------
// Fused 2D ReAdam step (Algorithm 1 with the factored scale), in two kernels:
//
//   kOptimizerStaticReadamFused  : reads r_{t-1}, c_{t-1}, mean(r_{t-1}) and U_{t-1}; updates p and U_t; and
//   accumulates
//                                  the row and column sums of G_t^2 into the scratch buffers acc_row / acc_col.
//   kReadamFinalizeStats         : r_t = beta2 * r_{t-1} + (1 - beta2) * acc_row / n_cols (same for c_t with n_rows),
//                                  mean_t = mean(r_t) per batch slice, and re-zeroes acc_row / acc_col.
//
// The new sums go to separate accumulators so that every block of the first kernel reads consistent t-1 statistics.
//
// Layout: the tensor is viewed as `batch` slices of n_rows x n_cols. A block of 256 threads covers a tile of
// TILE_ROWS x TILE_COLS elements, TILE_COLS = (256 / TILE_ROWS) * N_PER_TH: thread t owns tile row t / THREADS_PER_ROW
// and N_PER_TH consecutive columns, i.e. exactly one packed byte of state1 (requires n_cols % N_PER_TH == 0, which
// keeps rows byte-aligned in the flat packed state1 layout). Each block processes `k_tiles` tiles stacked down the rows
// of one batch slice, so the thread's columns stay the same and the column partial sums stay in registers:
//   - row sums: logical-warp reduction over the threads of a tile row -> one atomic per row per tile (two for
//     TILE_ROWS = 4 on 32-wide warps, whose 64-thread rows span two warps),
//   - column sums: registers across the k_tiles tiles, a shared-memory reduction over the tile rows at the end ->
//     one atomic per column per block.
// TILE_ROWS = 4 / 8 give full 32-byte sectors for the state1 bytes of a tile row, 16 / 32 suit narrow matrices.
//
// Non-finite gradients are skipped (treated as 0) in the statistics so a single NaN/Inf cannot poison r and c.
// Float atomics make the statistics non-deterministic in the last bits from run to run.
// ---------------------------------------------------------------------------------------------------------------------
template <typename T, int OPTIMIZER_BITS, int TILE_ROWS>
__launch_bounds__(256, 3) __global__ void kOptimizerStaticReadamFused(
    T* __restrict__ const p, T* __restrict__ const g, unsigned char* __restrict__ const state1,
    float* __restrict__ const state2_row, float* __restrict__ const state2_col, float* __restrict__ const state2_mean,
    float* __restrict__ const acc_row, float* __restrict__ const acc_col, const float beta1, const float beta2,
    const float eps, const int step, const float lr, const float weight_decay, const float decay_ratio, const int batch,
    const int n_rows, const int n_cols, const int k_tiles
) {
    constexpr int NUM_THREADS = 256;
    constexpr int N_PER_TH = 8 / OPTIMIZER_BITS;
    constexpr int THREADS_PER_ROW = NUM_THREADS / TILE_ROWS;
    constexpr int TILE_COLS = THREADS_PER_ROW * N_PER_TH;
    constexpr int LOGICAL_WARP = THREADS_PER_ROW < BNB_WARP_SIZE ? THREADS_PER_ROW : BNB_WARP_SIZE;
    static_assert(NUM_THREADS % TILE_ROWS == 0, "TILE_ROWS must divide the block size");

    typedef bnb_cub::WarpReduce<float, LOGICAL_WARP> RowReduce;
    __shared__ typename RowReduce::TempStorage row_storage[NUM_THREADS / LOGICAL_WARP];
    __shared__ float smem_col[TILE_COLS];

    const float at = __fdividef(1.0f - beta1, 1.0f - __powf(beta1, step));
    const float beta2_tprev = 1.0f - __powf(beta2, step - 1);
    const float bt = __fdividef(1.0f - beta2, 1.0f - __powf(beta2, step));
    const float eps_sq = eps * eps;

    const int local_row = threadIdx.x / THREADS_PER_ROW;
    const int local_col = (threadIdx.x % THREADS_PER_ROW) * N_PER_TH;
    const int col0 = blockIdx.x * TILE_COLS + local_col;
    // n_cols % N_PER_TH == 0, so either all N_PER_TH columns of this thread exist or none does.
    const bool col_valid = col0 < n_cols;

    const int rows_per_group = TILE_ROWS * k_tiles;
    const int groups_per_slice = (n_rows + rows_per_group - 1) / rows_per_group;
    const int num_groups = batch * groups_per_slice;

    float col_prev[N_PER_TH];
    float col_acc[N_PER_TH];
    float s1_vals[N_PER_TH];
    bool s1_in_decay[N_PER_TH];

    // grid-stride over (batch slice, row group); a block never mixes batch slices, so its column sums belong to one
    // slice of acc_col.
    for (int group = blockIdx.y; group < num_groups; group += gridDim.y) {
        const int b = group / groups_per_slice;
        const int group_row0 = (group % groups_per_slice) * rows_per_group;
        const float mean_prev = state2_mean[b];

        for (int i = threadIdx.x; i < TILE_COLS; i += NUM_THREADS)
            smem_col[i] = 0.0f;
#pragma unroll
        for (int j = 0; j < N_PER_TH; j++) {
            col_acc[j] = 0.0f;
            col_prev[j] = col_valid ? state2_col[b * n_cols + col0 + j] : 0.0f;
        }

        for (int k = 0; k < k_tiles; k++) {
            const int row = group_row0 + k * TILE_ROWS + local_row; // row within the batch slice
            float row_part = 0.0f;

            if (col_valid && row < n_rows) {
                const int slice_row = b * n_rows + row;
                const float row_prev = state2_row[slice_row];
                const int64_t base = (int64_t)slice_row * n_cols + col0;
                const unsigned char packed = state1[base / N_PER_TH];

#pragma unroll
                for (int j = 0; j < N_PER_TH; j++) {
                    const float g_f = (float)g[base + j];
                    const bool finite = !isnan(g_f) && !isinf(g_f);
                    if (finite) {
                        if (step == 1) {
                            // U_1 = sign(G_1) with sign(0) = 0
                            s1_vals[j] = (float)((g_f > 0.0f) - (g_f < 0.0f));
                            s1_in_decay[j] = false;
                        } else {
                            // S_{t-1} from the bias-corrected rank-1 reconstruction (Algorithm 1, lines 8-10)
                            float s2_val = __fdividef(row_prev * col_prev[j], mean_prev + eps_sq);
                            s2_val = sqrtf(__fdividef(s2_val, beta2_tprev));
                            const float z_val = __fdividef(g_f, s2_val + eps);
                            const float u_prev = dequantize_update<OPTIMIZER_BITS>(packed, j, eps);
                            s1_vals[j] = __fdividef(
                                ((1.0f - at) * u_prev) + (at * z_val), sqrtf(1.0f - bt + (bt * z_val * z_val)) + eps
                            );
                            s1_in_decay[j] = (fabsf(s1_vals[j]) > (fabsf(z_val) * decay_ratio));
                        }
                        const float g2 = g_f * g_f;
                        col_acc[j] += g2;
                        row_part += g2;
                    } else {
                        s1_vals[j] = 0.0f;
                        s1_in_decay[j] = false;
                    }

                    float p_f = (float)p[base + j];
                    if (finite)
                        p_f -= lr * s1_vals[j];
                    if (weight_decay > 0.0f)
                        p_f *= (1.0f - (lr * weight_decay));
                    p[base + j] = (T)p_f;
                }

                state1[base / N_PER_TH] = quantize_update<OPTIMIZER_BITS>(s1_vals, s1_in_decay, eps);
            }

            // Row sum over the threads of this tile row (all threads take part; invalid ones contribute 0).
            row_part = RowReduce(row_storage[threadIdx.x / LOGICAL_WARP]).Sum(row_part);
            if (threadIdx.x % LOGICAL_WARP == 0 && row < n_rows && row_part != 0.0f)
                atomicAdd(&acc_row[b * n_rows + row], row_part);
            __syncwarp();
        }

        // Column sums: combine the TILE_ROWS threads that share a column, then one atomic per column.
        __syncthreads(); // smem_col zeroed by all threads before anyone adds
        if (col_valid) {
#pragma unroll
            for (int j = 0; j < N_PER_TH; j++)
                if (col_acc[j] != 0.0f)
                    atomicAdd(&smem_col[local_col + j], col_acc[j]);
        }
        __syncthreads();
        for (int i = threadIdx.x; i < TILE_COLS; i += NUM_THREADS) {
            const int col = blockIdx.x * TILE_COLS + i;
            if (col < n_cols && smem_col[i] != 0.0f)
                atomicAdd(&acc_col[b * n_cols + col], smem_col[i]);
        }
        __syncthreads(); // smem_col is reset by the next group
    }
}

// r_t = beta2 * r_{t-1} + (1 - beta2) * acc_row / n_cols, c_t likewise with n_rows, mean_t = mean over rows of r_t (per
// batch slice). Blocks [0, batch) handle the rows and the mean of one batch slice each; the remaining blocks handle
// the columns. Re-zeroes the accumulators.
template <int NUM_THREADS>
__global__ void kReadamFinalizeStats(
    float* __restrict__ const state2_row, float* __restrict__ const state2_col, float* __restrict__ const state2_mean,
    float* __restrict__ const acc_row, float* __restrict__ const acc_col, const float beta2, const int batch,
    const int n_rows, const int n_cols
) {
    if (blockIdx.x < batch) {
        typedef bnb_cub::BlockReduce<float, NUM_THREADS> BlockReduce;
        __shared__ typename BlockReduce::TempStorage reduce_storage;

        const int b = blockIdx.x;
        const float inv_cols = 1.0f / (float)n_cols;
        float sum = 0.0f;
        for (int r = threadIdx.x; r < n_rows; r += NUM_THREADS) {
            const int idx = b * n_rows + r;
            const float v = beta2 * state2_row[idx] + (1.0f - beta2) * (acc_row[idx] * inv_cols);
            state2_row[idx] = v;
            acc_row[idx] = 0.0f;
            sum += v;
        }
        sum = BlockReduce(reduce_storage).Sum(sum);
        if (threadIdx.x == 0)
            state2_mean[b] = sum / (float)n_rows;
    } else {
        const float inv_rows = 1.0f / (float)n_rows;
        const int total = batch * n_cols;
        for (int idx = (blockIdx.x - batch) * NUM_THREADS + threadIdx.x; idx < total;
             idx += (gridDim.x - batch) * NUM_THREADS) {
            state2_col[idx] = beta2 * state2_col[idx] + (1.0f - beta2) * (acc_col[idx] * inv_rows);
            acc_col[idx] = 0.0f;
        }
    }
}

// Inputs:
//  A [rows, cols]
// Outputs:
//  rowStats [rows]
//  out [rows, cols]
template <typename T, int THREADS, int SPARSE_DECOMP>
__launch_bounds__(1024, BNB_MAX_THREADS_PER_SM / 1024) __global__
    void kInt8VectorQuant(T* __restrict__ A, int8_t* out, float* rowStats, float threshold, int rows, int cols) {

    using BlockReduceT = bnb_cub::BlockReduce<T, THREADS>;

    // One block per row.
    // Threads load column values in a striped arrangement.
    // e.g. t0 reads row[0], row[0+nthreads], ..
    // and  t1 reads row[1], row[1+nthreads], ..
    // Each thread will determine its local absmax.
    // We then do a blockwise reduction to determine the row's absmax.

    __shared__ typename BlockReduceT::TempStorage temp_storage;
    __shared__ T smem_row_absmax;

    const int row_id = blockIdx.x;
    const T* row_data = A + (row_id * cols);

    // Threads will read the row values in a striped access pattern and find a local absmax.
    T row_local_absmax = -FLT_MIN;
    for (int i = threadIdx.x; i < cols; i += THREADS) {
        const T absval = fabsf(__ldcs(&(row_data[i])));

        // For sparse decomposition, values outside of the threshold are not to be
        // included when calculating the row's absmax.
        if constexpr (SPARSE_DECOMP) {
            row_local_absmax = fmaxf(row_local_absmax, absval < T(threshold) ? absval : row_local_absmax);
        } else {
            row_local_absmax = fmaxf(row_local_absmax, absval);
        }
    }

    // Reduce thread-local absmax across the block.
    const T row_absmax = BlockReduceT(temp_storage).Reduce(row_local_absmax, BNB_MAX_OP, cols);
    if (threadIdx.x == 0) {
        // Save our block's absmax to shared memory for the quantization step.
        rowStats[row_id] = smem_row_absmax = row_absmax;
    }
    __syncthreads();

    // Quantize row-wise.
    const float scale = __fdividef(127.0f, smem_row_absmax);
    for (int i = threadIdx.x; i < cols; i += THREADS) {
        float val = row_data[i];

        if constexpr (SPARSE_DECOMP) {
            // For sparse decomposition, we do not want to quantize the outliers.
            // Instead they're zeroed out.
            out[row_id * cols + i] = fabs(val) < threshold ? __float2int_rn(val * scale) : 0;
        } else {
            out[row_id * cols + i] = __float2int_rn(val * scale);
        }
    }
}

template __global__ void kInt8VectorQuant<half, 1024, 0>(
    half* __restrict__ A, int8_t* out, float* rowStats, float threshold, int rows, int cols
);
template __global__ void kInt8VectorQuant<half, 1024, 1>(
    half* __restrict__ A, int8_t* out, float* rowStats, float threshold, int rows, int cols
